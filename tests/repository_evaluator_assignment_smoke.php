<?php
ob_start();
require __DIR__ . '/repository_evaluations_smoke.php';
$migration->up();
$forge->addColumn('oai_pmh', ['submitted_by' => ['type' => 'INT', 'null' => true]]);
$manager = $users->insert(['name' => 'Assignment manager', 'email' => 'assignment-manager@example.test', 'password' => password_hash('password123', PASSWORD_DEFAULT)]);
$evaluator = $users->insert(['name' => 'Eligible evaluator', 'email' => 'eligible@example.test', 'password' => password_hash('password123', PASSWORD_DEFAULT)]);
$expired = $users->insert(['name' => 'Expired evaluator', 'email' => 'expired@example.test', 'password' => password_hash('password123', PASSWORD_DEFAULT)]);
$managerRule = $rules->where('code', 'site-manager')->first();
$evaluatorRule = $rules->where('code', 'evaluator')->first();
$links->insert(['user_id' => $manager, 'rule_id' => $managerRule['id'], 'starts_at' => '2000-01-01', 'ends_at' => '2099-12-31']);
$links->insert(['user_id' => $evaluator, 'rule_id' => $evaluatorRule['id'], 'starts_at' => date('Y-m-d'), 'ends_at' => date('Y-m-d')]);
$links->insert(['user_id' => $evaluator, 'rule_id' => $evaluatorRule['id'], 'starts_at' => '2000-01-01', 'ends_at' => '2099-12-31']);
$links->insert(['user_id' => $expired, 'rule_id' => $evaluatorRule['id'], 'starts_at' => '2000-01-01', 'ends_at' => '2000-12-31']);
$eligible = $links->activeEvaluators();
check(count(array_filter($eligible, fn ($user) => (int) $user['id'] === (int) $evaluator)) === 1, 'Eligible users are distinct and inclusive at boundaries');
check(!in_array($expired, array_column($eligible, 'id')), 'Expired evaluator excluded');
session()->set(['logged_in' => true, 'user_id' => $manager]);
$evaluationModel = new App\Models\RepositoryEvaluationModel();
$db->table('oai_pmh')->where('id', $repoId)->update(['submitted_by' => $evaluator]);
controller(App\Controllers\Repositories::class, 'POST', ['evaluator_id' => $evaluator])->assignEvaluator($repoId);
check($evaluationModel->countAllResults() === 0, 'Submitter cannot evaluate own repository');
$db->table('oai_pmh')->where('id', $repoId)->update(['submitted_by' => null]);
$response = controller(App\Controllers\Repositories::class, 'POST', ['evaluator_id' => $evaluator])->assignEvaluator($repoId);
check(str_contains($response->getHeaderLine('Location'), 'tab=evaluators'), 'Return to evaluator tab');
$row = $evaluationModel->where('oai_pmh_id', $repoId)->where('evaluator_id', $evaluator)->first();
check($row && (int) $row['assigned_by'] === (int) $manager && $row['status'] === 'assigned', 'Assignment saved with audit data');
controller(App\Controllers\Repositories::class, 'POST', ['evaluator_id' => $evaluator])->assignEvaluator($repoId);
check($evaluationModel->countAllResults() === 1, 'Duplicate prevented');
controller(App\Controllers\Repositories::class, 'POST', ['evaluator_id' => $expired])->assignEvaluator($repoId);
controller(App\Controllers\Repositories::class, 'POST', ['evaluator_id' => $manager])->assignEvaluator($repoId);
check($evaluationModel->countAllResults() === 1, 'Expired and non-evaluator profiles rejected');
session()->set('user_id', $evaluator);
check(controller(App\Controllers\Repositories::class, 'POST', ['evaluator_id' => $evaluator])->assignEvaluator($repoId)->getStatusCode() === 403, 'Regular evaluator cannot assign');
ob_end_clean();
echo "PASS: active evaluator list, audit fields, duplicate assignments and administrator access (SQLite memory).\n";
